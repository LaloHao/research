import { describe, expect, it } from 'vitest'
import { renderSummaryMarkdown } from '../../../src/main/summary/markdown'
import { sampleExtraction, sampleSummary } from '../../helpers/summaries'

describe('renderSummaryMarkdown', () => {
  it('renders a readable summary with evidence and classification', () => {
    const md = renderSummaryMarkdown(
      'Drain',
      sampleSummary({ method: { value: 'Fixed depth tree', status: 'verified', evidence: [{ quote: 'we use a tree', page: 3, found: true }] } }),
      sampleExtraction({ technique: { values: ['ner'], proposed: ['tokenization'], status: 'generated', evidence: [] } })
    )
    expect(md.startsWith('# Drain\n')).toBe(true)
    expect(md).toContain('## Method\n\nFixed depth tree')
    expect(md).toContain('> "we use a tree" (p. 3)')
    expect(md).toContain('- **technique**: ner (proposed: tokenization)')
    expect(md).toContain('- **relevance**: 4 — j')
  })

  it('shows who generated a field, under its content', () => {
    const md = renderSummaryMarkdown(
      'Drain',
      sampleSummary({ tldr: { value: 'short', status: 'generated', evidence: [], origin: { model: 'claude-sonnet-5', at: '2026-10-08T12:00:00.000Z', prompt_version: 1 } } }),
      sampleExtraction()
    )
    expect(md).toContain('## TL;DR\n\nshort\n\n_Generated by claude-sonnet-5 on 2026-10-08._')
  })

  it('omits the line for a field without an origin', () => {
    const md = renderSummaryMarkdown('Drain', sampleSummary(), sampleExtraction())
    expect(md).not.toContain('_Generated by')
  })

  it('renders the relation to the thesis', () => {
    const md = renderSummaryMarkdown('Drain', sampleSummary(), {
      ...sampleExtraction(),
      thesis_relation: {
        text: 'Directly informs sanitization choices.',
        research_questions: ['RQ1', 'RQ2'],
        score: 4,
        justification: 'addresses RQ1',
        status: 'generated',
        evidence: [{ quote: 'we mask tokens', page: 2, found: true }]
      }
    })
    expect(md).toContain('## Relation to the thesis\n\nDirectly informs sanitization choices.')
    expect(md).toContain('RQ1, RQ2')
    expect(md).toContain('Score: 4/5 — addresses RQ1')
    expect(md).toContain('> "we mask tokens" (p. 2)')
  })

  it('has no thesis section without a relation', () => {
    expect(renderSummaryMarkdown('Drain', sampleSummary(), sampleExtraction())).not.toContain('Relation to the thesis')
  })
})
